export function getPainCategory(categoryId) {
  return PAIN_CATEGORIES.find((category) => category.id === categoryId) ?? PAIN_CATEGORIES[0];
}

export function getPainEntry(entryId) {
  return DTM_PAIN_LIBRARY.find((entry) => entry.id === entryId) ?? null;
}

export function buildPainEntryUrl(entry, origin = '') {
  const base = origin || 'https://sound-fix-ecfcf.web.app';
  try {
    const url = new URL('/library', base);
    url.searchParams.set('entry', entry.id);
    url.searchParams.set('source', 'library_share');
    return url.toString();
  } catch {
    return `/library?entry=${encodeURIComponent(entry.id)}&source=library_share`;
  }
}

export function buildPainShareText(entry, origin = '') {
  const category = getPainCategory(entry.category);
  const url = buildPainEntryUrl(entry, origin);
  const lines = [
    `${entry.title}。`,
    '',
    `Sound.backの制作悩みライブラリに「${category.label}」の相談例として追加しています。`,
    '自分の悩みを言葉にする時の叩き台にどうぞ。',
    '',
    url,
    '#DTM #DTMer',
  ];
  return lines.join('\n');
}

export function searchPainLibrary(items, { query = '', category = 'all', tag = '' } = {}) {
  const normalizedQuery = query.trim().toLowerCase();
  const normalizedTag = tag.trim().toLowerCase();

  return items.filter((entry) => {
    if (category !== 'all' && entry.category !== category) return false;

    const haystack = [
      entry.title,
      entry.summary,
      entry.prompt,
      ...entry.tags,
      getPainCategory(entry.category).label,
    ].join(' ').toLowerCase();

    if (normalizedQuery && !haystack.includes(normalizedQuery)) return false;
    if (normalizedTag && !entry.tags.some((itemTag) => itemTag.toLowerCase() === normalizedTag)) return false;

    return true;
  });
}

export function getPopularPainTags(limit = 18) {
  const counts = new Map();

  DTM_PAIN_LIBRARY.forEach((entry) => {
    entry.tags.forEach((tag) => {
      counts.set(tag, (counts.get(tag) ?? 0) + 1);
    });
  });

  return Array.from(counts.entries())
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0], 'ja'))
    .slice(0, limit)
    .map(([tag, count]) => ({ tag, count }));
}
